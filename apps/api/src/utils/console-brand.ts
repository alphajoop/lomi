const LINKS = [
  { label: 'Open Source', url: 'https://github.com/lomiafrica/lomi.' },
  { label: 'Careers', url: 'https://lomi.africa/careers' },
  { label: 'Status', url: 'https://status.lomi.africa' },
] as const;

let bannerIndex = -1;

const getNextBanner = (): string => {
  bannerIndex = (bannerIndex + 1) % BANNERS.length;
  const banner = BANNERS.at(bannerIndex) ?? BANNERS.at(0);
  if (!banner) return '';

  return banner.join('\n');
};

/** Plain-text lomi. banner (same content as website/dashboard devtools console). */
export const getBrandText = (): string => {
  const banner = getNextBanner();
  const links = LINKS.map(({ label, url }) => `- ${label} ${url}`).join('\n');

  return `▲\n\n${banner}\n\n${links}`;
};

/** Prints the lomi. banner when the API process starts. */
export const printConsoleBrand = (): void => {
  console.log(`\n${getBrandText()}\n`);
};
